/**
 * Generates synthetic PrusaSlicer-style G-code samples for the tests.
 * The ASCII layout (trailing stats comments + "prusaslicer_config" block) follows what PrusaSlicer writes;
 * The .bgcode samples are real output of Prusa's own libbgcode encoder (test/fixtures), made from synthetic G-code.
 * Neither is a real slicer export, so always try a real file from your own PrusaSlicer before relying on this.
 */
import fs from 'node:fs';
import path from 'node:path';

export interface SampleOpts {
  generator?: string; model?: string; type?: string; colour?: string; grams?: number; time?: string;
  nozzleTemp?: number; bedTemp?: number; extra?: string[]; nozzle?: number; lines?: number; noMeta?: boolean;
}

export function asciiGcode(o: SampleOpts = {}): string {
  const g = o.generator ?? 'PrusaSlicer 2.9.2';
  const model = o.model ?? 'MK4S', type = o.type ?? 'PLA', colour = o.colour ?? '#FF8000';
  const nt = o.nozzleTemp ?? 215, bt = o.bedTemp ?? 60;
  const out: string[] = [];
  out.push(`; generated by ${g} on 2026-10-30 at 09:15:00 UTC`, '');
  out.push('; thumbnail begin 16x16 100', '; AAAA', '; thumbnail end', '');
  out.push(`M862.3 P "${model}" ; printer model check`, 'M862.1 P0.4 A0 F1 ; nozzle check', 'M115 U6.1.0', 'G90', 'M83');
  out.push(`M140 S${bt}`, `M104 S${nt}`, `M190 S${bt}`, `M109 S${nt}`, 'G28', ';LAYER_CHANGE', ';Z:0.2');
  for (let i = 0; i < (o.lines ?? 2000); i++) out.push(`G1 X${(i % 200).toFixed(3)} Y${((i * 7) % 200).toFixed(3)} E0.0${i % 9}`);
  for (const e of o.extra ?? []) out.push(e);
  out.push('M104 S0', 'M140 S0', 'M84', '');
  if (!o.noMeta) {
    const g2 = o.grams ?? 12.34;
    out.push(`; filament used [mm] = ${(g2 * 335).toFixed(2)}`, `; filament used [cm3] = ${(g2 / 1.24).toFixed(2)}`, `; filament used [g] = ${g2}`, '; filament cost = 0.31',
      `; total filament used [g] = ${g2}`, '; total filament cost = 0.31', `; estimated printing time (normal mode) = ${o.time ?? '1h 12m 5s'}`, '; estimated first layer printing time (normal mode) = 1m 40s', '');
    out.push('; prusaslicer_config = begin', '; layer_height = 0.2', `; nozzle_diameter = ${o.nozzle ?? 0.4}`, `; filament_type = ${type}`, `; filament_colour = ${colour}`,
      `; printer_model = ${model}`, '; printer_settings_id = Original Prusa MK4S Input Shaper 0.4 nozzle', '; max_layer_z = 45.2', '; prusaslicer_config = end');
  }
  return out.join('\n') + '\n';
}

export function writeSamples(dir: string): Record<string, string> {
  fs.mkdirSync(dir, { recursive: true });
  const files: Record<string, string | Buffer> = {
    'good.gcode': asciiGcode(),
    'good-red.gcode': asciiGcode({ colour: '#D62828' }),
    'petg.gcode': asciiGcode({ type: 'PETG', colour: '#1A1A1A', nozzleTemp: 240, bedTemp: 80 }),
    'too-hot.gcode': asciiGcode({ type: 'PETG', nozzleTemp: 300 }),
    'too-heavy.gcode': asciiGcode({ grams: 900 }),
    'too-long.gcode': asciiGcode({ time: '1d 3h 10m 0s' }),
    'abs.gcode': asciiGcode({ type: 'ABS', nozzleTemp: 255, bedTemp: 100 }),
    'wrong-printer.gcode': asciiGcode({ model: 'MINI' }),
    'wrong-nozzle.gcode': asciiGcode({ nozzle: 0.6 }),
    'cura.gcode': asciiGcode({ generator: 'Cura_SteamEngine 5.6.0' }),
    'forbidden.gcode': asciiGcode({ extra: ['M502 ; factory reset', 'M500', 'M997'] }),
    'pauses.gcode': asciiGcode({ extra: ['M600 ; colour change'] }),
    'multicolor.gcode': asciiGcode({ type: 'PLA;PLA', colour: '"#FF0000";"#00FF00"' }),
    'nometa.gcode': asciiGcode({ noMeta: true }),
    'notgcode.stl': 'solid x\nendsolid x\n',
  };
  const paths: Record<string, string> = {};
  for (const [n, c] of Object.entries(files)) { const p = path.join(dir, n); fs.writeFileSync(p, c); paths[n] = p; }
  const fx = path.resolve('test/fixtures');
  for (const [name, src] of Object.entries({ 'good.bgcode': 'sample-slicer-style.bgcode', 'hot.bgcode': 'sample-hot.bgcode', 'deflate.bgcode': 'sample-deflate.bgcode' })) {
    const p = path.join(dir, name); fs.copyFileSync(path.join(fx, src), p); paths[name] = p;
  }
  return paths;
}

