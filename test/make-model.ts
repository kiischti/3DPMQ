/**
 * Deterministic test model written like PrusaSlicer would: a 20 mm cube (perimeter + zig-zag infill, with retractions
 * and travel moves) and a cylinder drawn with G2 arcs, 10 layers of 0.2 mm.
 *   cube:     X 50..70, Y 50..70      cylinder: centre (100,60), radius 10
 * Per layer: 4 perimeter + 4 infill segments + one full arc (flattened into 158 segments at 0.4 mm).
 */
export interface ModelOpts { relativeE?: boolean; noSpaces?: boolean; layers?: number; inches?: boolean; metadata?: boolean }
export const MODEL_SEGMENTS_PER_LAYER = 4 + 4 + 158;

export function modelGcode(o: ModelOpts = {}): string {
  const rel = o.relativeE ?? true, layers = o.layers ?? 10, k = o.inches ? 1 / 25.4 : 1;
  const n = (v: number) => (v * k).toFixed(4).replace(/\.?0+$/, '');
  const out: string[] = ['; generated by PrusaSlicer 2.9.2 on 2026-11-03 at 00:00:00 UTC', o.inches ? 'G20' : 'G21', 'G90', rel ? 'M83' : 'M82', 'G92 E0'];
  let e = 0;
  const ex = (de: number) => { e += de; return n(rel ? de : e).replace(/^$/, '0'); };
  const w = 0.04; // mm of filament per mm of path
  for (let i = 1; i <= layers; i++) {
    const z = i * 0.2;
    out.push(';LAYER_CHANGE', `;Z:${z.toFixed(3)}`, `G1 Z${n(z)} F720`);
    out.push(';TYPE:External perimeter', `G1 X${n(50)} Y${n(50)} F9000`);
    for (const [x, y] of [[70, 50], [70, 70], [50, 70], [50, 50]]) out.push(`G1 X${n(x)} Y${n(y)} E${ex(20 * w)} F1800`);
    out.push(';TYPE:Internal infill');
    let dir = 1;
    for (const y of [54, 58, 62, 66]) {
      out.push(`G1 E${ex(-0.8)} F2400`, `G1 X${n(dir > 0 ? 52 : 68)} Y${n(y)} F9000`, `G1 E${ex(0.8)} F2400`);
      out.push(`G1 X${n(dir > 0 ? 68 : 52)} Y${n(y)} E${ex(16 * w)} F3600`);
      dir = -dir;
    }
    out.push(';TYPE:Perimeter', `G1 E${ex(-0.8)}`, `G1 X${n(110)} Y${n(60)} F9000`, `G1 E${ex(0.8)}`);
    out.push(`G2 X${n(110)} Y${n(60)} I${n(-10)} J0 E${ex(2 * Math.PI * 10 * w)} F1800`);
    out.push(`G1 E${ex(-0.8)}`);
  }
  out.push('M104 S0', 'M140 S0', 'M84');
  if (o.metadata) { // statistics + config block as PrusaSlicer writes them, so that the file passes the request checks
    out.push('', '; filament used [mm] = 900.00', '; filament used [g] = 2.70', '; total filament used [g] = 2.70', '; estimated printing time (normal mode) = 12m 30s', '',
      '; prusaslicer_config = begin', '; layer_height = 0.2', '; nozzle_diameter = 0.4', '; filament_type = PLA', '; filament_colour = #FF8000', '; printer_model = MK4S',
      '; printer_settings_id = Original Prusa MK4S', '; max_layer_z = 2', '; prusaslicer_config = end');
  }
  const text = out.join('\n') + '\n';
  return o.noSpaces ? text.split('\n').map((l) => (/^G[0-3]\b/.test(l) ? l.replace(/;.*/, '').replace(/\s+/g, '') : l)).join('\n') : text;
}
