  ins.run('PLA', 'Black', '#1a1a1a');
  ins.run('PLA', 'White', '#f2f2f2');
  ins.run('PLA', 'Red', '#d62828');
  ins.run('PETG', 'Black', '#1a1a1a');
  ins.run('PETG', 'Clear', '#dfeff5');
