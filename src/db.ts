import { DatabaseSync } from 'node:sqlite';
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

export const DATA_DIR = path.resolve(process.env.DATA_DIR ?? './data');
export const UPLOAD_DIR = path.join(DATA_DIR, 'uploads');
fs.mkdirSync(UPLOAD_DIR, { recursive: true });

export const db = new DatabaseSync(path.join(DATA_DIR, 'makerqueue.db'));
db.exec('PRAGMA journal_mode = WAL; PRAGMA foreign_keys = ON;');

db.exec(`
CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY, value TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS filaments (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  material TEXT NOT NULL,          -- PLA, PETG, ...
  colour_name TEXT NOT NULL,
  colour_hex TEXT NOT NULL DEFAULT '#cccccc',
  in_stock INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS printers (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  name TEXT NOT NULL,
  base_url TEXT NOT NULL,          -- e.g. http://192.168.1.50
  username TEXT NOT NULL DEFAULT 'maker',
  password TEXT NOT NULL DEFAULT '',
  storage TEXT NOT NULL DEFAULT 'usb',
  model TEXT NOT NULL DEFAULT '',  -- matched against printer_model in the G-code, e.g. MK4S
  nozzle REAL,                     -- mm, optional
  enabled INTEGER NOT NULL DEFAULT 1,
  auto_start INTEGER NOT NULL DEFAULT 0,
  bed_clear INTEGER NOT NULL DEFAULT 0,
  loaded_filament_id INTEGER REFERENCES filaments(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS requests (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  user_name TEXT NOT NULL,
  user_email TEXT NOT NULL DEFAULT '',
  filament_id INTEGER REFERENCES filaments(id) ON DELETE SET NULL,
  notes TEXT NOT NULL DEFAULT '',
  file_name TEXT NOT NULL,
  file_path TEXT NOT NULL,
  file_size INTEGER NOT NULL,
  meta_json TEXT NOT NULL DEFAULT '{}',
  issues_json TEXT NOT NULL DEFAULT '[]',
  grams REAL,
  seconds INTEGER,
  status TEXT NOT NULL DEFAULT 'pending',
  -- pending | approved | rejected | printing | done | failed | cancelled
  reject_reason TEXT NOT NULL DEFAULT '',
  reviewed_by TEXT NOT NULL DEFAULT '',
  approved_at TEXT,
  priority INTEGER NOT NULL DEFAULT 0,
  printer_id INTEGER REFERENCES printers(id) ON DELETE SET NULL,
  started_at TEXT,
  finished_at TEXT,
  last_progress REAL NOT NULL DEFAULT 0,
  seen_printing INTEGER NOT NULL DEFAULT 0,
  remote_name TEXT NOT NULL DEFAULT '',
  cancel_token TEXT NOT NULL,
  error TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS idx_requests_status ON requests(status);

CREATE TABLE IF NOT EXISTS audit (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  ts TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  actor TEXT NOT NULL,
  action TEXT NOT NULL,
  request_id INTEGER,
  detail TEXT NOT NULL DEFAULT ''
);
`);

// ---------- rules ----------
export interface Rules {
  allowedMaterials: string[];
  maxHours: number;            // per print, 0 = unlimited
  maxGrams: number;            // per print, 0 = unlimited
  maxNozzleTemp: number;       // °C, highest M104/M109 S value allowed
  maxBedTemp: number;          // °C
  maxFileMB: number;
  requirePrusaSlicer: boolean; // reject files that were not generated by PrusaSlicer
  allowMulticolor: boolean;    // more than one filament used
  maxActivePerUser: number;    // pending + approved + printing, 0 = unlimited
  monthlyGramQuota: number;    // grams per user (by name) per calendar month, 0 = unlimited
  requireEmail: boolean;
}

export const DEFAULT_RULES: Rules = {
  allowedMaterials: ['PLA', 'PETG'],
  maxHours: 12,
  maxGrams: 300,
  maxNozzleTemp: 260,
  maxBedTemp: 90,
  maxFileMB: 200,
  requirePrusaSlicer: true,
  allowMulticolor: false,
  maxActivePerUser: 3,
  monthlyGramQuota: 0,
  requireEmail: false,
};

export function getRules(): Rules {
  const row = db.prepare('SELECT value FROM settings WHERE key = ?').get('rules') as { value: string } | undefined;
  return { ...DEFAULT_RULES, ...(row ? JSON.parse(row.value) : {}) };
}

export function setRules(r: Partial<Rules>): Rules {
  const merged = { ...getRules(), ...r };
  db.prepare('INSERT INTO settings(key,value) VALUES(?,?) ON CONFLICT(key) DO UPDATE SET value=excluded.value')
    .run('rules', JSON.stringify(merged));
  return merged;
}

export function getSecret(): string {
  if (process.env.SESSION_SECRET) return process.env.SESSION_SECRET;
  const row = db.prepare('SELECT value FROM settings WHERE key = ?').get('secret') as { value: string } | undefined;
  if (row) return row.value;
  const s = crypto.randomBytes(32).toString('hex');
  db.prepare('INSERT INTO settings(key,value) VALUES(?,?)').run('secret', s);
  return s;
}

export function audit(actor: string, action: string, requestId?: number, detail = ''): void {
  db.prepare('INSERT INTO audit(actor, action, request_id, detail) VALUES (?,?,?,?)')
    .run(actor, action, requestId ?? null, detail);
}

