export interface GcodeMeta {
  format: 'gcode' | 'bgcode';
  generator: string;               // e.g. "PrusaSlicer 2.9.2"
  printerModel: string;            // printer_model, e.g. MK4S
  printerSettingsId: string;
  filamentTypes: string[];         // one per extruder/filament slot used
  filamentColours: string[];       // hex strings
  grams?: number;                  // total filament weight
  seconds?: number;                // estimated print time (normal mode)
  layerHeight?: number;
  nozzleDiameter?: number;
  maxZ?: number;
  keys: number;                    // how many metadata keys were found (diagnostics)
}

export type Level = 'error' | 'warn' | 'info';
export interface Issue { level: Level; code: string; message: string }

// ---------------------------------------------------------------- helpers
const num = (v: string | undefined): number | undefined => {
  if (v === undefined) return undefined;
  const m = v.replace(/"/g, '').split(/[;,]/)[0].trim();
  const n = parseFloat(m);
  return Number.isFinite(n) ? n : undefined;
};

/** Sum all values in "1.2, 3.4" or "1.2;3.4" lists. */
const sumList = (v: string | undefined): number | undefined => {
  if (v === undefined) return undefined;
  const parts = v.replace(/"/g, '').split(/[;,]/).map((s) => parseFloat(s.trim())).filter(Number.isFinite);
  return parts.length ? parts.reduce((a, b) => a + b, 0) : undefined;
};

const list = (v: string | undefined): string[] =>
  v === undefined ? [] : v.split(';').map((s) => s.replace(/"/g, '').trim()).filter(Boolean);

/** "1d 2h 3m 4s" -> seconds */
export function parseDuration(s: string | undefined): number | undefined {
  if (!s) return undefined;
  let total = 0;
  let found = false;
  for (const m of s.matchAll(/(\d+)\s*([dhms])/g)) {
    found = true;
    const n = parseInt(m[1], 10);
    total += n * ({ d: 86400, h: 3600, m: 60, s: 1 } as const)[m[2] as 'd' | 'h' | 'm' | 's'];
  }
  return found ? total : undefined;
}

function metaFromKeys(format: 'gcode' | 'bgcode', kv: Record<string, string>, generator: string): GcodeMeta {
  const types = list(kv['filament_type']);
  const colours = list(kv['filament_colour']);
  // "filament used [g]" is per filament; "total filament used [g]" is the sum when present
  const grams = num(kv['total filament used [g]']) ?? sumList(kv['filament used [g]']);
  const seconds = parseDuration(kv['estimated printing time (normal mode)']);
  return {
    format,
    generator,
    printerModel: (kv['printer_model'] ?? '').replace(/"/g, '').trim(),
    printerSettingsId: (kv['printer_settings_id'] ?? '').replace(/"/g, '').trim(),
    filamentTypes: types,
    filamentColours: colours,
    grams,
    seconds,
    layerHeight: num(kv['layer_height']),
    nozzleDiameter: num(kv['nozzle_diameter']),
    maxZ: num(kv['max_layer_z']),
    keys: Object.keys(kv).length,
  };
}

// ---------------------------------------------------------------- ASCII .gcode
const HEAD_BYTES = 64 * 1024;
const TAIL_BYTES = 768 * 1024;

function readRange(fd: number, start: number, len: number): string {
  const buf = Buffer.alloc(len);
  const n = fs.readSync(fd, buf, 0, len, start);
  return buf.subarray(0, n).toString('utf8');
}

function parseAscii(file: string): GcodeMeta {
  const size = fs.statSync(file).size;
  const fd = fs.openSync(file, 'r');
  try {
    const head = readRange(fd, 0, Math.min(HEAD_BYTES, size));
    const tailLen = Math.min(TAIL_BYTES, size);
    const tail = readRange(fd, size - tailLen, tailLen);
    const kv: Record<string, string> = {};
    const re = /^;\s*([^=\n]+?)\s*=\s*(.*?)\s*$/;
    for (const line of (head + '\n' + tail).split(/\r?\n/)) {
      if (!line.startsWith(';')) continue;
      const m = re.exec(line);
      if (m) kv[m[1]] = m[2];
    }
    // "; filament used [g] = 4.74" lines can also be written as "; total filament used [g] = 4.74; total filament cost = 0.13"
    // on one line by some versions -> split on "; " when a second "key = value" is glued on
    for (const line of tail.split(/\r?\n/)) {
      if (!line.startsWith(';') || !line.includes('; ')) continue;
      for (const seg of line.split(/;\s+/)) {
        const m = /^([^=]+?)\s*=\s*(.*)$/.exec(seg.trim());
        if (m && !(m[1] in kv)) kv[m[1]] = m[2];
      }
    }
    const gen = /^;\s*generated by\s+(.+?)(?:\s+on\s+\d{4}-.*)?$/im.exec(head)?.[1]?.trim() ?? '';
    if (!kv['printer_model']) {
      // fall back to the M862.3 P "MK4S" printer-model check in the start G-code
      const m = /M862\.3\s+P\s*"([^"]+)"/.exec(head + tail);
      if (m) kv['printer_model'] = m[1];
    }
    return metaFromKeys('gcode', kv, gen);
  } finally {
    fs.closeSync(fd);
  }
}

// ---------------------------------------------------------------- binary .bgcode (decoder lives in bgcode.ts)
function parseBgcode(file: string): GcodeMeta {
  const { kv, generator } = readBgcodeMetadata(file);
  return metaFromKeys('bgcode', kv, generator);
}

/** Scans the whole file for temperatures and risky commands, for both plain and binary G-code. */
export async function scanFile(file: string, fileName: string): Promise<ScanResult> {
  return detectFormat(fileName) === 'bgcode' ? scanBgcode(file) : scanAscii(file);
}

export function detectFormat(fileName: string): 'gcode' | 'bgcode' | null {
  const l = fileName.toLowerCase();
  if (l.endsWith('.bgcode')) return 'bgcode';
  if (l.endsWith('.gcode') || l.endsWith('.gco') || l.endsWith('.g')) return 'gcode';
  return null;
}

export function parseMeta(file: string, fileName: string): GcodeMeta {
  const f = detectFormat(fileName);
  if (f === 'bgcode') return parseBgcode(file);
  return parseAscii(file);
}

// ---------------------------------------------------------------- validation
export interface PrinterLite {
  id: number; name: string; model: string; nozzle: number | null; enabled: number; loaded_filament_id: number | null;
}
export interface FilamentLite { id: number; material: string; colour_name: string; colour_hex: string; in_stock: number }

export const normModel = (s: string) => s.toUpperCase().replace(/[^A-Z0-9]/g, '');

/** Exact match after normalising: MK4 must not match MK4S (different printers, different firmware model checks). */
export function modelEquals(gcodeModel: string, printerModel: string): boolean {
  const a = normModel(gcodeModel), b = normModel(printerModel);
  return !!a && a === b;
}

export function validate(
  meta: GcodeMeta | null,
  scan: ScanResult | null,
  rules: Rules,
  ctx: { fileName: string; fileSize: number; filament?: FilamentLite | null; printers: PrinterLite[]; parseError?: string },
): Issue[] {
  const out: Issue[] = [];
  const err = (code: string, message: string) => out.push({ level: 'error', code, message });
  const warn = (code: string, message: string) => out.push({ level: 'warn', code, message });
  const info = (code: string, message: string) => out.push({ level: 'info', code, message });

  if (!detectFormat(ctx.fileName)) {
    err('file-type', 'Only sliced G-code files (.gcode or .bgcode) are accepted. Slice your model in PrusaSlicer first and export G-code.');
    return out;
  }
  if (ctx.fileSize > rules.maxFileMB * 1024 * 1024) err('file-size', `File is larger than ${rules.maxFileMB} MB.`);
  if (ctx.parseError || !meta) {
    err('unreadable', `Could not read the G-code metadata${ctx.parseError ? ` (${ctx.parseError})` : ''}. Re-export from PrusaSlicer.`);
    return out;
  }
  if (meta.keys < 5) err('no-metadata', 'No slicer metadata found in this file. Please export directly from PrusaSlicer.');

  if (rules.requirePrusaSlicer && !/prusaslicer|prusa-slicer/i.test(meta.generator)) {
    err('slicer', `This file was generated by "${meta.generator || 'an unknown program'}". Please slice with PrusaSlicer.`);
  }

  // printer model
  const enabled = ctx.printers.filter((p) => p.enabled);
  if (!meta.printerModel) {
    err('printer-model', 'The file does not say which printer model it was sliced for. Select the correct printer profile in PrusaSlicer.');
  } else {
    const candidates = enabled.filter((p) => modelEquals(meta.printerModel, p.model));
    if (enabled.length === 0) warn('no-printers', 'No printers are configured yet; the request will wait in the queue.');
    else if (candidates.length === 0) {
      const known = [...new Set(enabled.map((p) => p.model).filter(Boolean))].join(', ') || 'none configured';
      err('printer-model', `This file is sliced for "${meta.printerModel}". Printers available here: ${known}.`);
    } else if (meta.nozzleDiameter !== undefined) {
      const nozzleOk = candidates.filter((p) => p.nozzle === null || Math.abs(p.nozzle - meta.nozzleDiameter!) < 0.001);
      if (nozzleOk.length === 0) {
        err('nozzle', `This file needs a ${meta.nozzleDiameter} mm nozzle; no matching ${meta.printerModel} has one.`);
      }
    }
  }

  // material
  const types = meta.filamentTypes.map((t) => t.toUpperCase());
  if (types.length === 0) err('material', 'The file does not contain a filament type.');
  if (types.length > 1 && !rules.allowMulticolor) err('multi-material', 'Multi-material / multi-colour prints are not allowed.');
  for (const t of types) {
    if (!rules.allowedMaterials.map((m) => m.toUpperCase()).includes(t)) {
      err('material-not-allowed', `Material "${t}" is not allowed. Allowed: ${rules.allowedMaterials.join(', ')}.`);
    }
  }
  if (ctx.filament) {
    if (!ctx.filament.in_stock) err('filament-stock', `${ctx.filament.material} ${ctx.filament.colour_name} is currently out of stock.`);
    if (types.length && !types.includes(ctx.filament.material.toUpperCase())) {
      err('filament-mismatch', `You selected ${ctx.filament.material} ${ctx.filament.colour_name}, but the file is sliced for ${types.join('/')}. Change the filament profile in PrusaSlicer or pick the matching filament.`);
    }
    const loaded = enabled.filter((p) => p.loaded_filament_id === ctx.filament!.id);
    if (enabled.length && loaded.length === 0) {
      info('filament-not-loaded', `${ctx.filament.material} ${ctx.filament.colour_name} is not loaded on any printer right now; staff will load it before your print starts.`);
    }
  }

  // size limits
  if (meta.seconds === undefined) warn('no-time', 'No print-time estimate found in the file.');
  else if (rules.maxHours > 0 && meta.seconds > rules.maxHours * 3600) {
    err('too-long', `Estimated print time is ${(meta.seconds / 3600).toFixed(1)} h; the limit is ${rules.maxHours} h.`);
  }
  if (meta.grams === undefined) warn('no-weight', 'No filament weight found in the file.');
  else if (rules.maxGrams > 0 && meta.grams > rules.maxGrams) {
    err('too-heavy', `This print uses ${meta.grams.toFixed(0)} g of filament; the limit is ${rules.maxGrams} g.`);
  }

  // G-code content
  if (scan?.scanned) {
    if (scan.maxNozzleTemp > rules.maxNozzleTemp) err('nozzle-temp', `Nozzle temperature ${scan.maxNozzleTemp} °C exceeds the limit of ${rules.maxNozzleTemp} °C.`);
    if (scan.maxBedTemp > rules.maxBedTemp) err('bed-temp', `Bed temperature ${scan.maxBedTemp} °C exceeds the limit of ${rules.maxBedTemp} °C.`);
    const bad = Object.entries(scan.flagged);
    if (bad.length) err('forbidden-gcode', `The file contains commands that change printer settings or firmware: ${bad.map(([c, n]) => `${c}×${n}`).join(', ')}.`);
    if (scan.filamentChanges > 0) warn('pauses', `The file pauses the printer ${scan.filamentChanges}× (M600/M0/M1). Someone must be at the printer.`);
  } else {
    warn('unscanned', 'The G-code commands in this file could not be checked automatically. Staff should review it more carefully.');
  }

  return out;
}

export const hasErrors = (issues: Issue[]) => issues.some((i) => i.level === 'error');
